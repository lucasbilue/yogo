GLYPHS: dict[str, list[str]] = {k: v.split("|") for k, v in _RAW.items()}


def glyph(ch: str) -> list[str]:
    """Look up a character, falling back to uppercase then to a blank cell."""
    if ch in GLYPHS:
        return GLYPHS[ch]
    if ch.upper() in GLYPHS:
        return GLYPHS[ch.upper()]
    return GLYPHS[" "]


def lit_indices(ch: str) -> list[int]:
    """Indices of the lit pixels, row-major, in natural drawing order."""
    rows = glyph(ch)
    return [y * 6 + x for y in range(6) for x in range(6) if rows[y][x] == "#"]
